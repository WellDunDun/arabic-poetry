"""
The sixteen Khalilian meters (+ al-Mutadarak) and the taf'ila families of free verse.

Patterns use '1' for a moving letter (/) and '0' for a still letter (0).
Each variant is (pattern, foot-name, cost, label).  cost 0 = canonical form,
small costs = common zihaf, larger = rare/licensed forms. Costs only rank
readings; they never make a line "broken".
"""
from dataclasses import dataclass, field
from typing import List, Tuple

V = Tuple[str, str, float, str]


def v(p, name, cost=0.0, label=''):
    return (p, name, cost, label or name)


