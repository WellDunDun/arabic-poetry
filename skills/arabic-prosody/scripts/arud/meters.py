@dataclass
class Form:
    meter: str
    name: str                 # تام / مجزوء / مخلع / مشطور / منهوك
    hashw: List[List[V]]      # inner positions of one hemistich
    arud: List[V]             # last foot of the sadr
    darb: List[V]             # last foot of the ajuz
    single: bool = False      # poem written as single hemistichs (mashtur / manhuk)
    rare: float = 0.0         # prior cost added for rare forms
    ending_pairs: dict = field(default_factory=dict)
    kharm: List[V] = field(default_factory=list)   # الخرم: first moving letter of a sadr dropped (meters opening on a watad)

    @property
    def key(self):
        return f'{self.meter}/{self.name}'


